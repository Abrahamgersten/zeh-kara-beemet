// The public page of the shared goal of the story groups (Avraham, 2026-11-25): "every 100 new members release a new
// chapter" of the serial "המפה המופלאה", with the chapters released so far, a members counter and two share buttons
// (the group invitation with Bezalel's invitation video, and the weekly status):
//   s/wondrous-map/index.html   https://abrahamgersten.github.io/zeh-kara-beemet/s/wondrous-map/
//
// The page is a shell: which chapters are open and the members count come from a small state file that
// רוני המתכנת/Tools/map_campaign/update.py pushes to the audio repo (map/state.json), so a new chapter or a new number
// needs no push of this site. Chapter 1 is written into the page as the fallback when the state file cannot be read.
// The chapters themselves (titles, pictures, recordings) come from CATEGORIES in js/app.js and are written to
// רוני המתכנת/Tools/map_campaign/chapters.json for the updater.
//
// Usage (from the site folder), after a chapter of the story changes or the page's wording changes:
//   node tools/build_map_campaign.mjs

