function loadCategories(appJsPath) {
  const src = fs.readFileSync(appJsPath, "utf8");
  const start = src.indexOf("const CATEGORIES = [");
  const end = src.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error(`CATEGORIES not found in ${appJsPath}`);
  return vm.runInNewContext(`(${src.slice(start + "const CATEGORIES = ".length, end + 2)})`, {});
}
const slugOf = (audio) => {
  const name = path.posix.basename(audio);
  return name.includes("-sfx") ? name.slice(0, name.lastIndexOf("-sfx")) : name.replace(/\.[^.]+$/, "");
};

const cats = loadCategories(path.join(REPO, "js/app.js"));
const cat = cats.find((c) => c.serial && (c.niches || []).some((n) => n.id === ID));
if (!cat) throw new Error(`no serial niche "${ID}" in js/app.js`);
const niche = cat.niches.find((n) => n.id === ID);
const chapters = (cat.episodes || [])
  .filter((e) => e.niche === ID && e.audio && !e.sample)
  .map((ep) => ({ slug: slugOf(ep.audio), title: ep.title, description: ep.description || "", image: ep.image || "", audio: ep.audio }));
if (!chapters.length) throw new Error(`"${ID}" has no chapters`);
for (const ch of chapters) {
  for (const rel of [ch.audio, ch.image].filter(Boolean)) {
    if (!fs.existsSync(path.join(REPO, rel))) throw new Error(`${ID}: missing file ${rel}`);
  }
}
fs.mkdirSync(path.dirname(CHAPTERS_OUT), { recursive: true });
fs.writeFileSync(CHAPTERS_OUT, JSON.stringify({ first_at: FIRST_AT, step: 100, chapters }, null, 1));

