let stale = 0;
let written = 0;

function emit(file, content) {
  // git on Windows (autocrlf) may hand the files back with CRLF - that is not a content change
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) return;
  if (CHECK) {
    stale += 1;
    console.log(`out of date: ${path.relative(REPO, file)}`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  written += 1;
}

for (const [lang, L] of Object.entries(LANGS)) {
  const outDir = path.join(REPO, L.langRoot, "s");
  const stories = [];
  const seen = new Set();
  for (const cat of loadCategories(path.join(REPO, L.appJs))) {
    if (cat.type !== "audio") continue;
    for (const ep of cat.episodes || []) {
      if (!ep.audio || ep.sample) continue;
      const slug = slugOf(ep.audio);
      if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`[${lang}] unexpected slug "${slug}" from ${ep.audio}`);
      if (seen.has(slug)) throw new Error(`[${lang}] two episodes share the slug "${slug}"`);
      seen.add(slug);
      for (const rel of [ep.audio, ...(ep.images || (ep.image ? [ep.image] : []))]) {
        if (!fs.existsSync(path.join(REPO, L.langRoot, rel))) throw new Error(`[${lang}] ${slug}: missing file ${rel}`);
      }
      emit(path.join(outDir, slug, "index.html"), pageHTML(L, lang, cat, ep, slug));
      const url = new URL(`${L.langRoot ? L.langRoot + "/" : ""}s/${slug}/`, SITE_URL).href;
      // shareText: what "share" sends - on the story page and on the episode's card on the site (js/app.js)
      const status = statusOf(lang, slug, url, L.langRoot ? "../" : "");
      stories.push(Object.assign({ slug, title: ep.title, category: cat.id, url, shareText: shareMessage(L, lang, cat, ep, slug, url) }, status ? { status } : {}));
    }
  }
  emit(path.join(outDir, "index.json"), JSON.stringify({ lang, stories }, null, 2) + "\n");

  // a page whose episode left the catalog must not stay public - only folders this script generated are removed
  for (const entry of fs.existsSync(outDir) ? fs.readdirSync(outDir, { withFileTypes: true }) : []) {
    if (!entry.isDirectory() || seen.has(entry.name)) continue;
    const index = path.join(outDir, entry.name, "index.html");
    if (!fs.existsSync(index) || !fs.readFileSync(index, "utf8").includes(MARKER)) continue;
    if (CHECK) {
      stale += 1;
      console.log(`no longer in the catalog: ${path.relative(REPO, index)}`);
    } else {
      fs.rmSync(path.join(outDir, entry.name), { recursive: true });
      console.log(`removed ${path.relative(REPO, path.join(outDir, entry.name))} (episode no longer in the catalog)`);
    }
  }
  console.log(`[${lang}] ${stories.length} story pages`);
}

if (CHECK) {
  console.log(stale ? `${stale} file(s) out of date - run: node tools/build_story_pages.mjs` : "story pages are up to date");
  process.exit(stale ? 1 : 0);
}
console.log(`${written} file(s) written`);
