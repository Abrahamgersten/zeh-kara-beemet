const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function loadCategories(appJsPath) {
  const src = fs.readFileSync(appJsPath, "utf8");
  const start = src.indexOf("const CATEGORIES = [");
  const end = src.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error(`CATEGORIES not found in ${appJsPath}`);
  return vm.runInNewContext(`(${src.slice(start + "const CATEGORIES = ".length, end + 2)})`, {});
}

function slugOf(audioPath) {
  const name = path.posix.basename(audioPath);
  return name.includes("-sfx") ? name.slice(0, name.lastIndexOf("-sfx")) : name.replace(/\.[^.]+$/, "");
}

// width/height of a JPEG or PNG, so the browser reserves the picture's space before it arrives (no layout jump).
function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b.length > 24 && b.readUInt32BE(0) === 0x89504e47) return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
  let i = 2;
  while (i + 9 < b.length && b[i] === 0xff) {
    const marker = b[i + 1];
    const len = b.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { width: b.readUInt16BE(i + 7), height: b.readUInt16BE(i + 5) };
    }
    i += 2 + len;
  }
  return null;
}

