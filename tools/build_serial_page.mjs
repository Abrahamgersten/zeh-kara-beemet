// One public page with ALL the chapters of one serial story (Avraham, 2026-11-19: "one link that holds the whole
// serial story", the gift of the parents' survey, and "tell people to save it"):
//   s/<niche>/index.html   https://abrahamgersten.github.io/zeh-kara-beemet/s/<niche>/
//
// The chapters come from CATEGORIES in js/app.js (the serials category: the niche + the episodes with ep.niche), so
// titles, pictures and recordings stay the site's own. The chapters play one after another (js/serial.js), without
// login. Its own marker, so tools/build_story_pages.mjs (which removes s/<folder>/ pages of ITS marker that left the
// catalog) never touches this page; a chapter slug is always <niche>-chNN, so the folder never collides with one.
//
// Usage (from the site folder), after a chapter of that serial is added or changed:
//   node tools/build_serial_page.mjs lazy-sleeper [--campaign=story-page]

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_URL = "https://abrahamgersten.github.io/zeh-kara-beemet/";
const MARKER = "<!-- generated by tools/build_serial_page.mjs - do not edit by hand -->";
const BRAND = "זה קרה באמת";

const id = process.argv[2];
if (!id || !/^[a-z0-9-]+$/.test(id)) {
  console.error("usage: node tools/build_serial_page.mjs <niche-id>");
  process.exit(2);
}

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function loadCategories(appJsPath) {
  const src = fs.readFileSync(appJsPath, "utf8");
  const start = src.indexOf("const CATEGORIES = [");
  const end = src.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error(`CATEGORIES not found in ${appJsPath}`);
  return vm.runInNewContext(`(${src.slice(start + "const CATEGORIES = ".length, end + 2)})`, {});
}

function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b.length > 24 && b.readUInt32BE(0) === 0x89504e47) return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
  let i = 2;
  while (i + 9 < b.length && b[i] === 0xff) {
    const marker = b[i + 1];
    const len = b.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { width: b.readUInt16BE(i + 7), height: b.readUInt16BE(i + 5) };
    }
    i += 2 + len;
  }
  return null;
}
const dims = (rel) => {
  const s = imageSize(path.join(REPO, rel));
  return s ? ` width="${s.width}" height="${s.height}"` : "";
};
const slugOf = (audio) => {
  const name = path.posix.basename(audio);
  return name.includes("-sfx") ? name.slice(0, name.lastIndexOf("-sfx")) : name.replace(/\.[^.]+$/, "");
};

const cats = loadCategories(path.join(REPO, "js/app.js"));
const cat = cats.find((c) => c.serial && (c.niches || []).some((n) => n.id === id));
if (!cat) throw new Error(`no serial niche "${id}" in js/app.js`);
const niche = cat.niches.find((n) => n.id === id);
const chapters = (cat.episodes || []).filter((e) => e.niche === id && e.audio && !e.sample);
if (!chapters.length) throw new Error(`"${id}" has no chapters`);
for (const ep of chapters) {
  for (const rel of [ep.audio, ep.image].filter(Boolean)) {
    if (!fs.existsSync(path.join(REPO, rel))) throw new Error(`${id}: missing file ${rel}`);
  }
}

const pageUrl = new URL(`s/${id}/`, SITE_URL).href;
const up = "../../";
const n = chapters.length;
const description = niche.blurb || "";
const shareText = `🎧 *${niche.name}*\nסיפור בהמשכים לילדים, ${n} פרקים להאזנה בחינם:\n${pageUrl}`;
const saveText = `🎧 ${niche.name}: כל ${n} הפרקים בקישור אחד\n${pageUrl}`;
const data = JSON.stringify({
  serial: id,
  lang: "he",
  chapters: chapters.map((ep) => slugOf(ep.audio)),
}).replace(/</g, "\\u003c");

